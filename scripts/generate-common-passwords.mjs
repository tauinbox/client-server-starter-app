#!/usr/bin/env node
/**
 * Regenerates shared/src/data/common-passwords.ts from a pinned SecLists
 * commit. Run it from any directory:
 *
 *   node scripts/generate-common-passwords.mjs
 *
 * then run `npm run format` in server/ so the output matches Prettier.
 *
 * The filter matches the password policy: only an entry that the length rule
 * would accept can reach the check, so a shorter one only costs memory.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = 'danielmiessler/SecLists';
const COMMIT = 'eccfbd405af82194e125a450a0076dbe4252d6f9';
const MIN_LENGTH = 8;
const TOP_ENTRIES = 10000;

const SOURCES = [
  {
    path: 'Passwords/Common-Credentials/Pwdb_top-100000.txt',
    limit: TOP_ENTRIES
  },
  {
    path: 'Passwords/Common-Credentials/Language-Specific/Russian_Pwdb_common-password-list-top-150.txt',
    limit: Infinity
  }
];

const rawUrl = (path) =>
  `https://raw.githubusercontent.com/${REPO}/${COMMIT}/${path}`;

async function fetchLines(path) {
  const res = await fetch(rawUrl(path));
  if (!res.ok) {
    throw new Error(`GET ${rawUrl(path)} -> ${res.status}`);
  }
  return (await res.text()).split(/\r?\n/);
}

const entries = new Set();
for (const source of SOURCES) {
  let taken = 0;
  for (const line of await fetchLines(source.path)) {
    if (taken >= source.limit) break;
    const entry = line.trim().toLowerCase();
    if (entry.length < MIN_LENGTH || entries.has(entry)) continue;
    entries.add(entry);
    taken++;
  }
  console.log(`${source.path}: ${taken} entries`);
}

const header = [
  '// GENERATED by scripts/generate-common-passwords.mjs - do not edit by hand.',
  `// Source: https://github.com/${REPO} (MIT licence), commit ${COMMIT}.`,
  '// Server and mock-server only: the list is too large for the client bundle.'
];

// MIT asks that the notice travel with any substantial portion of the lists,
// so it is fetched from the same commit and embedded in the output.
const licence = (await fetchLines('LICENSE')).join('\n').trimEnd();
if (licence.includes('*/')) {
  throw new Error('LICENSE text would close the comment block');
}

const body = [...entries].map((e) => `  ${JSON.stringify(e)},`).join('\n');
const out =
  `${header.join('\n')}\n` +
  `/*\n${licence}\n*/\n` +
  `export const COMMON_PASSWORDS: ReadonlySet<string> = new Set([\n${body}\n]);\n`;

const target = join(
  dirname(fileURLToPath(import.meta.url)),
  '../shared/src/data/common-passwords.ts'
);
writeFileSync(target, out);
console.log(`Wrote ${entries.size} entries to ${target}`);
